#include "jpg/IDCT2D.hpp"
#include <gtest/gtest.h>

TEST(IDCT2DTest, InverseDCT1)
{
	int32_t input[64] = {
	   24545,   39394,   19938,   29889,    4263,    7997,   35829,    5799,
	   62306,   46404,   34390,   51457,   62186,   32451,   12114,   12843,
	   47971,    1349,   28307,   13085,   63283,    2253,   63542,    2964,
	   39233,   63564,   19085,   33700,   52979,   59593,   50799,   21320,
	   10224,   54554,   40098,   38824,   19963,   16959,   61571,   25472,
	   10223,   13915,    9141,    3044,    6401,   43419,   58643,   17783,
	    3806,   11916,   19145,   39816,   44841,   20428,   39183,   54312,
       56765,   12019,   24009,   11175,   28845,   34083,   60415,   23380
	};

	std::vector<double> expectedOutput = {
		2.2388, -0.6432,  0.5000,  0.0795,  0.2055,  0.2622, -0.3038,  0.2186,
	   -0.3272,  0.5938, -0.4058,  0.2653,  0.1166,  0.0124,  0.0598,  0.0748,
		0.1801, -0.1134,  0.0482, -0.0958,  0.1971,  0.0746,  0.1793,  0.1042,
       -0.3166,  0.2567, -0.0580, -0.2248, -0.2712, -0.0380, -0.0139, -0.4374,
        0.4729,  0.1119,  0.2163, -0.0500, -0.0819,  0.0646, -0.0120, -0.2180,
       -0.0500, -0.0904, -0.0695, -0.0477,  0.0488, -0.1599, -0.0219, -0.3170,
       -0.2311, -0.0636,  0.3380,  0.1706, -0.2660,  0.2349, -0.0161,  0.1498,
       -0.2477,  0.0152, -0.0209, -0.3760, -0.0026,  0.1269, -0.2531,  0.1908
	};

	auto outputBlock = IDCT2D::InverseDCT(input);

	ASSERT_EQ(outputBlock.size(), expectedOutput.size());
	for (size_t i = 0; i < outputBlock.size(); ++i) {
		EXPECT_NEAR(outputBlock[i], expectedOutput[i], 0.00001);
	}
}